BEGIN;

ALTER TABLE category ADD COLUMN IF NOT EXISTS code VARCHAR(50) UNIQUE;

UPDATE category
SET code = CASE name
    WHEN '다로리의 요즘' THEN 'VILLAGE_NEWS'
    WHEN '프로젝트 후속' THEN 'PROJECT_FOLLOW_UP'
    WHEN '구인/참여' THEN 'RECRUITMENT'
    WHEN '제철 정보' THEN 'SEASONAL'
END
WHERE code IS NULL;

